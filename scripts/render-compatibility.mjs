import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { builtinModelCatalog, providerEnvFor } from '../dist/config.js';
import { HARNESSES } from '../dist/harness/registry.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, 'docs', 'compatibility.md');
const pricing = JSON.parse(readFileSync(join(root, 'src', 'cost', 'pricing.json'), 'utf8'));

const harnessMeta = {
  'claude-code': {
    isolation: 'private runtime; `Read`, `Grep`, and `Glob` only',
    cost: 'provider-reported; unknown on malformed output',
  },
  codex: {
    isolation: 'kernel profile; sealed checkout read-only; minimal tool environment',
    cost: 'token-estimated; unknown without usage',
  },
  'grok-build': {
    isolation: 'private runtime and kernel profile; no MCP, web, memory, or subagents',
    cost: 'provider-reported when present; unknown otherwise',
  },
  'kimi-code': {
    isolation: 'private runtime; `Read`, `Grep`, and `Glob` only',
    cost: 'usage-estimated; unknown without usage records',
  },
  deepseek: {
    isolation: 'private runtime; workspace-confined read/search tools; read-only sandbox',
    cost: 'provider-usage estimated; unknown without usage events',
  },
  opencode: {
    isolation: 'private HOME/XDG; mutating, shell, web, and task tools removed',
    cost: 'provider-reported per step; unknown on malformed output',
  },
  'generic-openai': {
    isolation: 'in-process path-confined read/search tools; one exact report write',
    cost: 'provider-reported only when declared; estimated or unknown fallback',
  },
};

const providerNames = {
  JUROR_ANTHROPIC_API_KEY: 'Anthropic',
  JUROR_OPENAI_API_KEY: 'OpenAI',
  JUROR_FIREWORKS_API_KEY: 'Fireworks',
  JUROR_XAI_API_KEY: 'xAI',
  JUROR_OPENROUTER_API_KEY: 'OpenRouter',
  JUROR_SCALEWAY_API_KEY: 'Scaleway',
};

for (const harnessId of Object.keys(HARNESSES)) {
  if (!harnessMeta[harnessId]) throw new Error(`compatibility: missing metadata for ${harnessId}`);
}

const entries = builtinModelCatalog().sort((a, b) => a.model.id.localeCompare(b.model.id));
for (const { model, presets } of entries) {
  if (presets.length === 0) throw new Error(`compatibility: built-in ${model.id} is in no preset`);
  const pricingKey = model.pricing_key ?? model.id;
  if (!pricing.models?.[pricingKey]) {
    throw new Error(`compatibility: built-in ${model.id} has no pricing entry ${pricingKey}`);
  }
  if (!HARNESSES[model.harness]) {
    throw new Error(`compatibility: built-in ${model.id} has no registered harness ${model.harness}`);
  }
}

function cell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function code(value) {
  return `\`${String(value).replaceAll('`', '\\`')}\``;
}

function pricingEvidence(model) {
  const key = model.pricing_key ?? model.id;
  const row = pricing.models[key];
  return `[${cell(row.updated)}](${row.source})`;
}

function costAccounting(model) {
  if (model.harness === 'generic-openai' && model.args?.usage_cost === 'usd') {
    return 'provider-reported; price fallback';
  }
  return harnessMeta[model.harness].cost;
}

const lines = [
  '# Compatibility matrix',
  '',
  '<!-- Generated by scripts/render-compatibility.mjs; do not edit by hand. -->',
  '',
  'This matrix is generated from the built-in model catalog, preset definitions, registered',
  'harnesses, and versioned pricing table. It describes tested Juror configuration, not a',
  'promise that an external provider will keep a model available. Run',
  '`npm run docs:compatibility` after changing any of those inputs.',
  '',
  `Pricing table last checked: **${cell(pricing.$meta.updated)}**.`,
  '',
  '## Built-in models',
  '',
  '| Model | Provider / Juror secret | Harness | Provider route | Presets | Cost accounting | Pricing evidence |',
  '|---|---|---|---|---|---|---|',
];

for (const { model, presets } of entries) {
  const provider = providerNames[model.secret] ?? 'Custom';
  const route = model.harness_model ?? model.id;
  lines.push(
    `| ${cell(model.label ?? model.id)}<br><sub>${code(model.id)}</sub> | ` +
      `${cell(provider)}<br><sub>${code(model.secret)}</sub> | ` +
      `${cell(HARNESSES[model.harness].label)}<br><sub>${code(model.harness)}</sub> | ` +
      `${code(route)} | ${presets.map(code).join(', ')} | ${cell(costAccounting(model))} | ` +
      `${pricingEvidence(model)} |`,
  );
}

lines.push(
  '',
  '## Harness boundaries',
  '',
  '| Harness | Credential name inside adapter | Repository/tool isolation | Cost behavior |',
  '|---|---|---|---|',
);

for (const [harnessId, harness] of Object.entries(HARNESSES).sort(([a], [b]) => a.localeCompare(b))) {
  const meta = harnessMeta[harnessId];
  lines.push(
    `| ${cell(harness.label)}<br><sub>${code(harnessId)}</sub> | ${code(providerEnvFor(harnessId))} | ` +
      `${cell(meta.isolation)} | ${cell(meta.cost)} |`,
  );
}

lines.push(
  '',
  'A configured model can still be skipped when its credential or harness executable is',
  'unavailable. Juror must show that degradation in the receipt and must never present a',
  'single successful reviewer as cross-model consensus.',
  '',
);

const rendered = `${lines.join('\n')}`;
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== rendered) {
    process.stderr.write('docs/compatibility.md is stale; run npm run docs:compatibility\n');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, rendered);
  process.stdout.write('updated docs/compatibility.md\n');
}
